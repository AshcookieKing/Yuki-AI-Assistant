// жесты «на речь»: лёгкое объясняющее движение одной или двумя руками
export function talkBeat(t, seed, amount) {
  const a = amount * (0.5 + 0.5 * Math.sin(t * 2.3 + seed));
  const side = Math.sin(seed * 7.1) > 0 ? 'L' : 'R';
  const both = Math.sin(seed * 3.3) > 0.4;
  const pose = (on) => (on ? { upper: [0, -0.35 * a, 0.12 * a], lower: [0, -0.9 * a, 0] } : null);
  return { L: pose(side === 'L' || both), R: pose(side === 'R' || both) };
}
